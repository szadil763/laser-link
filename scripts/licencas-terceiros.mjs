// (dependências de produção do agente e da interface) e o texto de cada licença.
// Uso: node scripts/licencas-terceiros.mjs   (rode depois de mudar dependências)
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("..", import.meta.url).pathname;
const npm = process.platform === "win32" ? "npm.cmd" : "npm";
const out = execFileSync(npm, ["ls", "--omit=dev", "--all", "--parseable"], { cwd: root, encoding: "utf8" });
const dirs = [...new Set(out.split(/\r?\n/).filter((d) => d.includes("node_modules")))];

