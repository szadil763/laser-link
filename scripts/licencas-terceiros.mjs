const entries = new Map();
for (const dir of dirs) {
  const pkg = JSON.parse(readFileSync(join(dir, "package.json"), "utf8"));
  if (pkg.name.startsWith("@laserlink/")) continue;
  const file = readdirSync(dir).find((f) => /^(licen[cs]e|copying)/i.test(f));
  let text = file ? readFileSync(join(dir, file), "utf8").trim() : "";
  let license = typeof pkg.license === "string" ? pkg.license : "ver texto";
  if (pkg.name === "clipper-lib") {
    license = "BSL-1.0 (Boost Software License 1.0)";
    text = `Clipper - Copyright (c) Angus Johnson 2010-2017. Tradução para JavaScript: Timo.\n\n${BOOST}\n\n---\n\nInclui trechos da biblioteca jsbn:\n\n${JSBN}`;
  }
  const key = `${pkg.name}@${pkg.version}`;
  if (!entries.has(key)) entries.set(key, { name: pkg.name, version: pkg.version, license, text });
}

const sorted = [...entries.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const lines = [
  "# Licenças de terceiros",
  "",
  "O LaserLink é software proprietário (veja `LICENSE`). Ele inclui as bibliotecas abaixo,",
  "que continuam sob as próprias licenças. Todas permitem uso comercial; os avisos de",
  "copyright e os textos das licenças estão reproduzidos aqui, como elas pedem.",
  "",
  "Arquivo gerado por `node scripts/licencas-terceiros.mjs`.",
  "",
  "| Biblioteca | Versão | Licença |",
  "|---|---|---|",
  ...sorted.map((e) => `| ${e.name} | ${e.version} | ${e.license} |`),
  "",
];
for (const e of sorted) {
  lines.push(`## ${e.name} ${e.version}`, "", `Licença: ${e.license}`, "", "```", e.text || "(o pacote não traz o texto da licença)", "```", "");
}
writeFileSync(join(root, "LICENCAS-DE-TERCEIROS.md"), lines.join("\n"));
console.log(`${sorted.length} bibliotecas listadas em LICENCAS-DE-TERCEIROS.md`);
